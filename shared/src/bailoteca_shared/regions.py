def normalize_comuna(text: str) -> str:
    nfd = unicodedata.normalize("NFD", text)
    no_marks = "".join(c for c in nfd if unicodedata.category(c) != "Mn")
    s = no_marks.lower()
    s = re.sub(r"['’.\-]", "", s)  # comillas, puntos, guiones
    return " ".join(s.split())


def regions() -> list[dict[str, str]]:
    return [{"slug": s, "name": n} for s, n in REGIONS]


def comunas_in_region(slug: str) -> list[str]:
    if slug not in REGION_SLUGS:
        raise ValueError(f"región desconocida: {slug!r}")
    return list(_COMUNAS_BY_REGION[slug])  # ya viene ordenado


_INDEX = {
    normalize_comuna(c): slug
    for slug, cs in _COMUNAS_BY_REGION.items()
    for c in cs
}


def region_slug_for_comuna(comuna: str | None) -> str | None:
    if not comuna or not comuna.strip():
        return None
    return _INDEX.get(normalize_comuna(comuna))
